def convert_sprite_to_hex(sprite_data):
    """
    Convert sprite data from strings of 0/1/2 to hex format.
    Each pixel uses 2 bits: 0=00 (empty), 1=01 (white), 2=10 (black)
    16 pixels per row = 32 bits = 4 bytes = 4 hex values
    
    Args:
        sprite_data: List of strings, each containing 16 characters (0, 1, or 2)
    
    Returns:
        List of strings, each containing 4 hex values separated by commas
    """
    hex_rows = []
    
    for row in sprite_data:
        if len(row) != 16:
            raise ValueError(f"Each row must have exactly 16 pixels, got {len(row)}")
          # Group into 4 bytes (8 bits each)
        # Each byte contains 4 pixels: leftmost pixel in bits 7-6, rightmost pixel in bits 1-0
        hex_values = []
        for i in range(0, 16, 4):  # Process 4 pixels at a time (not 8 bits)
            # Get 4 pixels and reverse their order so leftmost pixel gets highest bits
            p0 = row[i]     # Leftmost pixel of this group
            p1 = row[i+1]
            p2 = row[i+2] 
            p3 = row[i+3]   # Rightmost pixel of this group
            
            # Convert to 2-bit values
            def pixel_to_bits(pixel):
                if pixel == ' ': return "00"    # Empty/Transparent
                elif pixel == '#': return "01"  # White
                elif pixel == '.': return "10"  # Black
                else: raise ValueError(f"Invalid pixel value: {pixel}")
            
            # Arrange bits: leftmost pixel in highest bits (7-6), rightmost in lowest bits (1-0)
            byte_bits = pixel_to_bits(p0) + pixel_to_bits(p1) + pixel_to_bits(p2) + pixel_to_bits(p3)
            hex_value = hex(int(byte_bits, 2))[2:].upper().zfill(2)
            hex_values.append(f"0x{hex_value}")
        
        hex_rows.append(", ".join(hex_values))
    
    return hex_rows

def print_converted_sprite(sprite_data, sprite_name="enemy_sprite"):
    """
    Print the converted sprite data in C++ array format
    """
    hex_rows = convert_sprite_to_hex(sprite_data)
    
    print("{", f"// {sprite_name}")
    for i, row in enumerate(hex_rows):
        comma = "," if i < len(hex_rows) - 1 else ""
        print(f"    {{{row}}}{comma}", end="\n" if i % 4 == 3 else " ")
    print("},")

